import random
import math
print("DEEPTHI GIRISH 1WN24CS088")
N = 8

def cost(board):
    conflicts = 0

    for i in range(N):
        for j in range(i + 1, N):
            if board[i] == board[j]:
                conflicts += 1
            elif abs(board[i] - board[j]) == abs(i - j):
                conflicts += 1

    return conflicts

def simulated_annealing(board):
    current = board[:]
    current_cost = cost(current)

    best = current[:]
    best_cost = current_cost

    T = 1000
    cooling_rate = 0.995

    while T > 0.01 and best_cost != 0:

        next_state = current[:]

        col = random.randint(0, N - 1)
        row = random.randint(0, N - 1)

        next_state[col] = row

        next_cost = cost(next_state)

        delta = current_cost - next_cost

        if delta > 0:
            current = next_state
            current_cost = next_cost

        else:
            probability = math.exp(delta / T)

            if random.random() < probability:
                current = next_state
                current_cost = next_cost

        if current_cost < best_cost:
            best = current[:]
            best_cost = current_cost

        T *= cooling_rate

    return best, best_cost


# User input
print("Enter the row position of each queen (1-8):")

board = []

for i in range(N):
    row = int(input(f"Queen {i + 1}: "))
    board.append(row - 1)

solution, conflicts = simulated_annealing(board)

print("\nFinal Board:")

for row in range(N):
    for col in range(N):
        if solution[col] == row:
            print("Q", end=" ")
        else:
            print(".", end=" ")
    print()

print("\nQueen placements:", [x + 1 for x in solution])
print("Conflicts:", conflicts)

if conflicts == 0:
    print("Solution found!")
else:
    print("No solution found in this run. Try again.")