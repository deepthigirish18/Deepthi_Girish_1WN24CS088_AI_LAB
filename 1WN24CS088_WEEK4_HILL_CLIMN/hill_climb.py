def calculate_cost(state):
    cost = 0
    n = len(state)

    for i in range(n):
        for j in range(i + 1, n):
            if state[i] == state[j]:
                cost += 1
            elif abs(state[i] - state[j]) == abs(i - j):
                cost += 1

    return cost


def get_neighbors(state):
    neighbors = []
    n = len(state)

    for i in range(n):
        for j in range(i + 1, n):
            new_state = state[:]
            new_state[i], new_state[j] = new_state[j], new_state[i]

            neighbors.append((new_state, i, j))

    return neighbors


def hill_climbing(state):
    current = state[:]
    step = 1

    while True:
        current_cost = calculate_cost(current)

        print("\nStep", step)
        print("Current state:", current)
        print("Current cost:", current_cost)

        if current_cost == 0:
            print("Goal state reached!")
            return current

        neighbors = get_neighbors(current)

        print("\nNeighbor states:")

        best_neighbor = current
        best_cost = current_cost

        for neighbor, i, j in neighbors:
            cost = calculate_cost(neighbor)

            print("Swap x" + str(i) + ", x" + str(j),
                  "->", neighbor, "Cost:", cost)

            if cost < best_cost:
                best_neighbor = neighbor
                best_cost = cost

        if best_cost >= current_cost:
            print("\nHill climbing stopped at local minimum.")
            return current

        current = best_neighbor
        step += 1


n = int(input("Enter number of queens: "))

print("Enter row positions for each queen (0 to", n - 1, ")")

state = []

for i in range(n):
    row = int(input("Enter row for queen x" + str(i) + ": "))
    state.append(row)

print("\nInitial state:", state)
print("Initial cost:", calculate_cost(state))

result = hill_climbing(state)

print("\nFinal state:", result)
print("Final cost:", calculate_cost(result))