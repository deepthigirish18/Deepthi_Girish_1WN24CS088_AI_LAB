from itertools import product
print("DEEPTHI GIRISH 1WN24CS088")
print("P\tQ\tR\tQ->P\tP->~Q\tQ|R\tKB")

models = []

for P, Q, R in product([False, True], repeat=3):

    q_imp_p = (not Q) or P
    p_imp_not_q = (not P) or (not Q)
    q_or_r = Q or R

    KB = q_imp_p and p_imp_not_q and q_or_r

    if KB:
        models.append((P, Q, R))

    print(
        P, Q, R,
        q_imp_p,
        p_imp_not_q,
        q_or_r,
        KB,
        sep="\t"
    )

print("\nModels of KB:")
for model in models:
    print(model)

# Query 1: KB entails R
entails_R = all(R for P, Q, R in models)

# Query 2: KB entails R -> P
entails_R_imp_P = all((not R) or P for P, Q, R in models)

# Query 3: KB entails Q -> R
entails_Q_imp_R = all((not Q) or R for P, Q, R in models)

print("\nKB entails R:", entails_R)
print("KB entails R -> P:", entails_R_imp_P)
print("KB entails Q -> R:", entails_Q_imp_R)